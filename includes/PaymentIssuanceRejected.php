/** Internal result of an explicit HTTP validation rejection without a resource identity. */
final class PaymentIssuanceRejected
{
    private $message;

    public function __construct(string $message)
    {
        $this->message = $message;
    }

    public function getMessage(): string
    {
        return $this->message;
    }
}
